//! Flat host value graph. UTF-16, IEEE numbers and object identity survive JSON.
use super::{MethodId, ModelSchema, PrototypeId};
use crate::compat::{ErrorCode, PeleError};
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};

#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct JsString(pub Vec<u16>);
impl std::borrow::Borrow<[u16]> for JsString {
    fn borrow(&self) -> &[u16] {
        &self.0
    }
}
impl From<&str> for JsString {
    fn from(value: &str) -> Self {
        Self(value.encode_utf16().collect())
    }
}
impl JsString {
    /// UTF-8 byte length bounds UTF-16 units. Keep common property lookups on
    /// the stack; long keys retain the ordinary owned conversion path.
    pub(crate) fn short_utf16<'a>(value: &str, buffer: &'a mut [u16; 64]) -> Option<&'a [u16]> {
        if value.len() > buffer.len() {
            return None;
        }
        let mut len = 0;
        for unit in value.encode_utf16() {
            buffer[len] = unit;
            len += 1;
        }
        Some(&buffer[..len])
    }

    pub fn well_formed(&self) -> Option<String> {
        String::from_utf16(&self.0).ok()
    }
    pub fn is(&self, value: &str) -> bool {
        self.0.iter().copied().eq(value.encode_utf16())
    }
}
mod number_bits {
    use serde::{Deserialize, Deserializer, Serializer};
    pub fn serialize<S: Serializer>(value: &f64, out: S) -> Result<S::Ok, S::Error> {
        out.serialize_str(&format!("{:016x}", value.to_bits()))
    }
    pub fn deserialize<'de, D: Deserializer<'de>>(input: D) -> Result<f64, D::Error> {
        let hex = String::deserialize(input)?;
        if hex.len() != 16 {
            return Err(serde::de::Error::custom("Invalid IEEE number bits"));
        }
        u64::from_str_radix(&hex, 16)
            .map(f64::from_bits)
            .map_err(serde::de::Error::custom)
    }
}
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", content = "value", rename_all = "camelCase")]
pub enum Atom {
    Undefined,
    Null,
    Bool(bool),
    Number(#[serde(with = "number_bits")] f64),
    String(u32),
    Ref(u32),
    BuiltinFunction(u32),
    HostReference(u32),
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Property {
    pub key: u32,
    pub value: Atom,
    /// Enumerable=1, writable=2, configurable=4.
    pub flags: u8,
}
/// Host runtime Error brands. Own fields stay in the ordinary identity arena;
/// stack/location diagnostics are generated by the receiving runtime.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ErrorObjectKind {
    Error,
    Pele,
    Type,
    Range,
    Syntax,
    Reference,
    Eval,
    Uri,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum Node {
    Error {
        #[serde(rename = "errorType")]
        error_type: ErrorObjectKind,
        properties: Vec<Property>,
    },
    /// A real schema-declared instance; ordinary Object constructors stay valid.
    Instance {
        prototype: PrototypeId,
        properties: Vec<Property>,
    },
    Object {
        properties: Vec<Property>,
    },
    /// Array length is implicit with its default writable descriptor. A
    /// nondefault own `length` Property preserves readonly length (flags 0);
    /// its numeric value agrees with the scalar length.
    Array {
        length: u32,
        properties: Vec<Property>,
    },
    Map {
        entries: Vec<(Atom, Atom)>,
        properties: Vec<Property>,
    },
    Set {
        values: Vec<Atom>,
        properties: Vec<Property>,
    },
    Date {
        #[serde(with = "number_bits")]
        milliseconds: f64,
        properties: Vec<Property>,
    },
}
impl Node {
    pub fn properties(&self) -> &[Property] {
        match self {
            Self::Error { properties, .. }
            | Self::Object { properties }
            | Self::Instance { properties, .. }
            | Self::Array { properties, .. }
            | Self::Map { properties, .. }
            | Self::Set { properties, .. }
            | Self::Date { properties, .. } => properties,
        }
    }
    pub fn properties_mut(&mut self) -> &mut Vec<Property> {
        match self {
            Self::Error { properties, .. }
            | Self::Object { properties }
            | Self::Instance { properties, .. }
            | Self::Array { properties, .. }
            | Self::Map { properties, .. }
            | Self::Set { properties, .. }
            | Self::Date { properties, .. } => properties,
        }
    }
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ModelGraph {
    pub version: u32,
    pub root: Atom,
    pub strings: Vec<JsString>,
    pub nodes: Vec<Node>,
}
fn invalid(message: &str) -> PeleError {
    PeleError::new(message, ErrorCode::Semantic)
}
impl ModelGraph {
    /// Validate an atom naming this arena. Builtin IDs need validate_schema.
    pub fn validate_atom(&self, a: &Atom) -> Result<(), PeleError> {
        match a {
            Atom::Ref(id) if *id as usize >= self.nodes.len() => {
                Err(invalid("Invalid public object reference"))
            }
            Atom::String(id) if *id as usize >= self.strings.len() => {
                Err(invalid("Invalid public string reference"))
            }
            _ => Ok(()),
        }
    }
    /// Schema checks cover native instance/function identities, not generic JS
    /// value coercion or family field validation. Codecs own those operations.
    pub fn validate_schema(&self, schema: &ModelSchema) -> Result<(), PeleError> {
        schema.validate()?;
        self.validate()?;
        let methods: HashSet<_> = schema.methods.iter().map(|m| m.id).collect();
        let prototypes: HashSet<_> = schema.prototypes.iter().map(|p| p.id).collect();
        let atom = |a: &Atom| -> Result<(), PeleError> {
            if let Atom::BuiltinFunction(id) = a {
                if !methods.contains(&MethodId(*id)) {
                    return Err(invalid("Unknown public builtin function"));
                }
            }
            Ok(())
        };
        atom(&self.root)?;
        for n in &self.nodes {
            if let Node::Instance { prototype, .. } = n {
                if !prototypes.contains(prototype) {
                    return Err(invalid("Unknown public instance prototype"));
                }
            }
            for p in n.properties() {
                atom(&p.value)?
            }
            match n {
                Node::Map { entries, .. } => {
                    for (k, v) in entries {
                        atom(k)?;
                        atom(v)?
                    }
                }
                Node::Set { values, .. } => {
                    for v in values {
                        atom(v)?
                    }
                }
                _ => {}
            }
        }
        Ok(())
    }
    pub fn validate(&self) -> Result<(), PeleError> {
        if self.version != 1 {
            return Err(invalid("Unsupported public graph version"));
        }
        let units = self
            .strings
            .iter()
            .try_fold(0usize, |n, s| n.checked_add(s.0.len()))
            .ok_or_else(|| invalid("Public graph size overflow"))?;
        if self.nodes.len() > 1_000_000 || self.strings.len() > 1_000_000 || units > 16_000_000 {
            return Err(PeleError::new(
                "Public model graph exceeds work budget",
                ErrorCode::Limit,
            ));
        }
        self.validate_atom(&self.root)?;
        let mut work = 0usize;
        for node in &self.nodes {
            let references = match node {
                Node::Map { entries, .. } => entries.len().saturating_mul(2),
                Node::Set { values, .. } => values.len(),
                _ => 0,
            };
            work = work
                .saturating_add(node.properties().len())
                .saturating_add(references);
            if work > 8_000_000 {
                return Err(PeleError::new(
                    "Public graph exceeds work budget",
                    ErrorCode::Limit,
                ));
            }
            for p in node.properties() {
                if p.key as usize >= self.strings.len() || p.flags & !7 != 0 {
                    return Err(invalid("Invalid public property"));
                }
                self.validate_atom(&p.value)?;
            }
            match node {
                Node::Map { entries, .. } => {
                    for (k, v) in entries {
                        self.validate_atom(k)?;
                        self.validate_atom(v)?;
                    }
                }
                Node::Set { values, .. } => {
                    for v in values {
                        self.validate_atom(v)?;
                    }
                }
                _ => {}
            }
        }
        Ok(())
    }
    pub fn root_properties(&self) -> Result<&[Property], PeleError> {
        match &self.root {
            Atom::Ref(id) => match self.nodes.get(*id as usize) {
                Some(Node::Object { properties } | Node::Instance { properties, .. }) => {
                    Ok(properties)
                }
                _ => Err(invalid("Public model root must be an object")),
            },
            _ => Err(invalid("Public model root must be an object")),
        }
    }
    pub fn field(&self, key: &str) -> Result<Option<&Atom>, PeleError> {
        Ok(self
            .root_properties()?
            .iter()
            .find(|p| self.strings[p.key as usize].is(key))
            .map(|p| &p.value))
    }
    pub fn text(&self, value: &Atom) -> Result<&JsString, PeleError> {
        match value {
            Atom::String(id) => self
                .strings
                .get(*id as usize)
                .ok_or_else(|| invalid("Invalid public string reference")),
            _ => Err(invalid("Expected a public string")),
        }
    }
}
/// Writer interns repeated strings. References can point forward or form cycles.
pub struct GraphWriter {
    graph: ModelGraph,
    strings: HashMap<JsString, u32>,
}
impl Default for GraphWriter {
    fn default() -> Self {
        Self {
            graph: ModelGraph {
                version: 1,
                root: Atom::Undefined,
                strings: vec![],
                nodes: vec![],
            },
            strings: HashMap::new(),
        }
    }
}
impl GraphWriter {
    pub fn string(&mut self, value: impl Into<JsString>) -> u32 {
        let value = value.into();
        if let Some(id) = self.strings.get(&value) {
            return *id;
        }
        let id = self.graph.strings.len() as u32;
        self.graph.strings.push(value.clone());
        self.strings.insert(value, id);
        id
    }
    pub fn node(&mut self, node: Node) -> u32 {
        let id = self.graph.nodes.len() as u32;
        self.graph.nodes.push(node);
        id
    }
    pub fn property(&mut self, key: &str, value: Atom) -> Property {
        let mut buffer = [0; 64];
        let id = JsString::short_utf16(key, &mut buffer)
            .and_then(|units| self.strings.get(units).copied())
            .unwrap_or_else(|| self.string(key));
        Property {
            key: id,
            value,
            flags: 7,
        }
    }
    pub fn finish(mut self, root: Atom) -> Result<ModelGraph, PeleError> {
        self.graph.root = root;
        self.graph.validate()?;
        Ok(self.graph)
    }
}
