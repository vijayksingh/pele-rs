// Static lexical class names preserve engine-generated call-without-new errors.
// This is a finite transport catalogue, not runtime source evaluation.
import fs from 'node:fs';
const fixture=JSON.parse(fs.readFileSync(process.argv[2]??'fixtures/public-constructor-reflection.json'));
const names=new Map();
for(const row of fixture.rows)for(const artifact of ['monolith','module']){
  const {name,length}=row[artifact];
  if(!/^[$A-Z_a-z][$\w]*$/.test(name)||![0,2].includes(length))throw new Error('Invalid pinned constructor shell');
  if(names.has(name)&&names.get(name)!==length)throw new Error('Conflicting pinned constructor shell');
  names.set(name,length);
}
if(fixture.rows.length!==23||names.size!==44)throw new Error('Changed pinned constructor catalogue');
const lines=['// Generated by scripts/generate-constructor-shells.mjs from pinned reflection.','// Only forwards the allocated receiver and untouched arguments to Rust ownership.','export function namedConstructor(name,initialize){','  switch(name){'];
for(const [name,arity]of names)lines.push(`    case ${JSON.stringify(name)}:return class ${name}{constructor(${arity===2?'_first,_second':''}){initialize(this,arguments);}};`);
lines.push("    default:throw new TypeError('Unknown authenticated constructor shell');",'  }','}','');
fs.writeFileSync(process.argv[3]??'bindings/web/constructor-shells.js',lines.join('\n'));
